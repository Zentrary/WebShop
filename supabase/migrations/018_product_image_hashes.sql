-- 018_product_image_hashes.sql
-- เก็บ "ลายนิ้วมือของรูปสินค้า" (dHash 64 บิต) ไว้ที่ตัวสินค้า
-- เพื่อให้หน้าแอดมินเตือนได้ว่า "รูปนี้ซ้ำกับสินค้าที่มีอยู่แล้ว" ก่อนบันทึก
--
-- * products.image_hashes = text[] ของ dHash (hex 16 ตัวอักษรต่อค่า)
--   เก็บได้หลายค่า เพราะสินค้า 1 ชิ้นมีได้หลายรูป (image_urls) และรูปเดียวกัน
--   อาจถูกบันทึกด้วยหลายครอป (รูปที่วางขาย 4:5 + รูปที่ตัวแก้ไขรูปสร้างเป็น 1:1)
-- * ค่าว่าง = ยังไม่มีลายนิ้วมือ → ระบบข้ามการตรวจรูปซ้ำของสินค้านั้น
--   (การตรวจชื่อ/SKU ยังทำงานตามปกติ)
--
-- ⚠️ สำคัญ: ค่า hash ต้องมาจากตัวแก้ไขรูปของเว็บเอง (src/core/image.js → dHash)
--    เพราะ dHash ไวต่อการครอป/รีไซซ์มาก รูปเดียวกันที่ครอปด้วยเครื่องมืออื่น
--    (เช่น ImageMagick) จะห่างกัน 15–30 บิต แล้วจะจับคู่กันไม่เจอ
--    ทางที่ถูกคือให้แอดมินอัปโหลดรูปผ่านฟอร์ม (ระบบคำนวณและบันทึกให้เอง)
--    แล้วค่อยปรับขนาด/ครอปด้วยตัวแก้ไขรูปในหน้าเว็บ

alter table public.products
  add column if not exists image_hashes text[] not null default '{}'::text[];

comment on column public.products.image_hashes is
  'dHash 64 บิต (hex) ของรูปสินค้า สร้างจากตัวแก้ไขรูปของเว็บ ใช้ตรวจรูปซ้ำในหน้าแอดมิน';

-- เผื่อมีข้อมูลชุดเก่าที่ใส่ค่า null ไว้
update public.products
   set image_hashes = '{}'::text[]
 where image_hashes is null;
